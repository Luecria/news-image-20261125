#!/usr/bin/env python3
"""Deterministically render local stories as a 1024px newspaper front page.

Measure full regional headlines, choose the largest fitting font, and justify
columns with uniform extra story gaps. No network, clock, or random input.
"""
import hashlib
import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'entry.png'
W = H = 1024
MARGIN, FRAME, COL_GAP = 30, 14, 22
COL_W = (W - 2 * MARGIN - 2 * COL_GAP) // 3
PAPER, INK = (251, 248, 241), (17, 17, 17)
RED, GRAY, LIGHT = (185, 28, 28), (107, 114, 128), (205, 200, 188)
FONT_ROOT = Path('/usr/share/fonts/truetype/dejavu')
SERIF_B, SANS, SANS_B = 'DejaVuSerif-Bold.ttf', 'DejaVuSans.ttf', 'DejaVuSans-Bold.ttf'
STORY_SIZES = (13, 12.75, 12.5, 12.25, 12, 11.75, 11.5, 11.25, 11)
# Keep the v1 footer position; justify the final story ink to eight pixels above it.
FOOTER_RULE_Y = 966
COLUMN_BOTTOM = FOOTER_RULE_Y - 8
FOOTER_TEXT = (
    'All stories dated 25 November 2026  ·  Unconfirmed reports are labelled CLAIM  ·  '
    'Image generated by code — no AI imagery'
)
COLUMNS = (
    ('NORTH AMERICA', 'EUROPE'),
    ('MIDDLE EAST', 'AFRICA'),
    ('LATIN AMERICA', 'ASIA-PACIFIC', 'WORLD'),
)


@lru_cache(maxsize=None)
def font(face, size):
    return ImageFont.truetype(str(FONT_ROOT / face), size)


def wrap(draw, text, face, width=COL_W):
    lines, current = [], ''
    for word in text.split():
        if draw.textlength(word, font=face) > width:
            raise ValueError(f'Word exceeds column width: {word!r}')
        trial = f'{current} {word}'.strip()
        if current and draw.textlength(trial, font=face) > width:
            lines.append(current)
            current = word
        else:
            current = trial
    if current:
        lines.append(current)
    return tuple(lines)


def center(draw, y, text, face, fill=INK):
    draw.text(((W - draw.textlength(text, font=face)) / 2, y), text,
              font=face, fill=fill)


def draw_top(draw, data):
    """Preserve v1 masthead and lead typography, wrapping and coordinates."""
    draw.rectangle((FRAME, FRAME, W - FRAME - 1, H - FRAME - 1), outline=INK, width=2)
    y = MARGIN + 4
    center(draw, y, data['title'], font(SERIF_B, 62))
    y += 74
    center(draw, y, 'WEDNESDAY  ·  25 NOVEMBER 2026', font(SANS_B, 15))
    y += 24
    total = len(data['leads']) + sum(len(s['stories']) for s in data['sections'])
    center(draw, y,
           f'ONE DAY IN WORLD NEWS  —  {total} STORIES  ·  7 REGIONS  ·  ALL SOURCED',
           font(SANS, 11), GRAY)
    y += 22
    draw.line(((MARGIN, y), (W - MARGIN, y)), fill=INK, width=3)
    y += 12
    draw.text((MARGIN, y), 'TOP STORIES', font=font(SANS_B, 12), fill=RED)
    lead_top = y + 20
    head, deck = font(SERIF_B, 19), font(SANS, 12)
    layouts = []
    for lead in data['leads']:
        # Keep the lead block exactly as displayed in the submitted version.
        heads = wrap(draw, lead['headline'], head)[:3]
        decks = wrap(draw, lead['deck'], deck)[:2]
        height = 16 + 18 * bool(lead['claim']) + len(heads) * 23
        height += 3 + len(decks) * 16 + 2 + 14
        layouts.append((heads, decks, height))
    lead_height = max(item[2] for item in layouts)
    for i, (lead, (heads, decks, _)) in enumerate(zip(data['leads'], layouts)):
        x, ly = MARGIN + i * (COL_W + COL_GAP), lead_top
        draw.text((x, ly), lead['kicker'], font=font(SANS_B, 11), fill=RED)
        ly += 16
        if lead['claim']:
            tag, tag_font = '  CLAIM  ', font(SANS_B, 10)
            tw = draw.textlength(tag, font=tag_font)
            draw.rectangle((x, ly + 2, x + tw, ly + 14), fill=RED)
            draw.text((x, ly + 2), tag, font=tag_font, fill=(255, 255, 255))
            ly += 18
        for line in heads:
            draw.text((x, ly), line, font=head, fill=INK)
            ly += 23
        ly += 3
        for line in decks:
            draw.text((x, ly), line, font=deck, fill=INK)
            ly += 16
        draw.text((x, ly + 2), 'Source: ' + lead['source'], font=font(SANS, 10), fill=GRAY)
        if i < 2:
            dx = x + COL_W + COL_GAP // 2
            draw.line(((dx, lead_top), (dx, lead_top + lead_height)), fill=LIGHT, width=1)
    rule_y = lead_top + lead_height + 10
    draw.line(((MARGIN, rule_y), (W - MARGIN, rule_y)), fill=INK, width=1)
    return rule_y + 12


@dataclass(frozen=True)
class StoryLayout:
    story: dict
    lines: tuple
    source_x: float
    source_y: float
    height: float
    ink_bottom: float


def measure_story(draw, story, size):
    face, source_font = font(SANS_B, size), font(SANS, 10)
    line_height = int(size * 1.26)
    prefix = '[CLAIM] ' if story['claim'] else ''
    lines = wrap(draw, prefix + story['headline'], face)
    source = '— ' + story['source']
    last_width = draw.textlength(lines[-1], font=face)
    inline = last_width + 6 + draw.textlength(source, font=source_font) <= COL_W
    source_x = last_width + 6 if inline else 0
    source_y = (len(lines) - 1) * line_height + 2 if inline else len(lines) * line_height
    # Line boxes already provide glyph clearance; add all inter-story spacing
    # through column justification rather than reserving v1's extra four pixels.
    height = len(lines) * line_height + (0 if inline else 13)
    ink_bottom = max(
        (len(lines) - 1) * line_height + draw.textbbox((0, 0), lines[-1], font=face)[3],
        source_y + draw.textbbox((0, 0), source, font=source_font)[3],
    )
    return StoryLayout(story, lines, source_x, source_y, height, ink_bottom)


def measure_columns(draw, sections, size):
    columns = []
    for names in COLUMNS:
        y, headers, stories = 0, [], []
        for name in names:
            headers.append((name, y))
            y += 24
            for story in sections[name]:
                block = measure_story(draw, story, size)
                stories.append((y, block))
                y += block.height
            y += 6
        bottom = max(y + block.ink_bottom for y, block in stories)
        columns.append((headers, stories, bottom))
    return columns


def draw_columns(draw, sections, size, columns, top):
    face, section_font = font(SANS_B, size), font(SANS_B, 12)
    metrics = []
    for ci, (headers, stories, natural_height) in enumerate(columns):
        x = MARGIN + ci * (COL_W + COL_GAP)
        extra_gap = (COLUMN_BOTTOM - top - natural_height) / (len(stories) - 1)
        assert extra_gap >= 0
        # Section headers move with the stories following them.
        for name, header_y in headers:
            preceding = sum(story_y < header_y for story_y, _ in stories)
            hy = top + header_y + preceding * extra_gap
            draw.text((x, hy), name, font=section_font, fill=RED)
            count = str(len(sections[name]))
            draw.text((x + COL_W - draw.textlength(count, font=section_font), hy),
                      count, font=section_font, fill=GRAY)
            draw.line(((x, hy + 16), (x + COL_W, hy + 16)), fill=INK, width=1)
        for index, (story_y, block) in enumerate(stories):
            sy = top + story_y + index * extra_gap
            for li, line in enumerate(block.lines):
                ly = sy + li * int(size * 1.26)
                if li == 0 and block.story['claim']:
                    prefix = '[CLAIM] '
                    draw.text((x, ly), prefix, font=face, fill=RED)
                    draw.text((x + draw.textlength(prefix, font=face), ly),
                              line[len(prefix):], font=face, fill=INK)
                else:
                    draw.text((x, ly), line, font=face, fill=INK)
            draw.text((x + block.source_x, sy + block.source_y),
                      '— ' + block.story['source'], font=font(SANS, 10), fill=GRAY)
        end = top + natural_height + (len(stories) - 1) * extra_gap
        assert abs(end - COLUMN_BOTTOM) < 0.001
        metrics.append({'column': ci + 1, 'stories': len(stories),
                        'extra_gap': round(extra_gap, 4), 'ink_bottom': end,
                        'footer_gap': FOOTER_RULE_Y - end})
    return metrics


def render(data):
    image = Image.new('RGB', (W, H), PAPER)
    draw = ImageDraw.Draw(image)
    top = draw_top(draw, data)
    sections = {section['name']: section['stories'] for section in data['sections']}
    assert set(sections) == {name for column in COLUMNS for name in column}
    for size in STORY_SIZES:
        columns = measure_columns(draw, sections, size)
        if max(column[2] for column in columns) <= COLUMN_BOTTOM - top:
            break
    else:
        raise ValueError('Columns do not fit at the minimum 11pt story font')
    metrics = draw_columns(draw, sections, size, columns, top)
    draw.line(((MARGIN, FOOTER_RULE_Y), (W - MARGIN, FOOTER_RULE_Y)), fill=INK, width=1)
    center(draw, FOOTER_RULE_Y + 8, FOOTER_TEXT, font(SANS, 10), GRAY)
    return image, size, metrics


def main():
    data = json.loads((ROOT / 'stories.json').read_text(encoding='utf-8'))
    image, size, metrics = render(data)
    image.save(OUT, format='PNG', optimize=True)
    encoded = OUT.read_bytes()
    if len(encoded) > 1048576:
        raise ValueError('PNG exceeds 1 MiB')
    print(f'wrote {OUT}')
    print(f'size_bytes={len(encoded)} dimensions={image.size} format=PNG')
    print(f"story_count={len(data['leads']) + sum(len(s['stories']) for s in data['sections'])}")
    print(f'story_font={size}')
    print('columns=' + json.dumps(metrics, sort_keys=True))
    print(f'sha256={hashlib.sha256(encoded).hexdigest()}')


if __name__ == '__main__':
    main()
